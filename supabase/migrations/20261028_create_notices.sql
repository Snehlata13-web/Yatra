DO $$
DECLARE
    warden_user_id_type text;
BEGIN
    SELECT format_type(a.atttypid, a.atttypmod)
    INTO warden_user_id_type
    FROM pg_attribute a
    WHERE a.attrelid = 'public.wardens'::regclass
      AND a.attname = 'user_id'
      AND NOT a.attisdropped;

    IF warden_user_id_type IS NULL THEN
        RAISE EXCEPTION 'Could not find public.wardens.user_id';
    END IF;

    EXECUTE format($create_table$
        CREATE TABLE IF NOT EXISTS public.notices (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            warden_user_id %s NOT NULL
                REFERENCES public.users(id) ON DELETE CASCADE,
            title varchar(200) NOT NULL
                CHECK (char_length(trim(title)) BETWEEN 1 AND 200),
            body text NOT NULL
                CHECK (char_length(trim(body)) BETWEEN 1 AND 10000),
            media jsonb NOT NULL DEFAULT '[]'::jsonb
                CHECK (CASE WHEN jsonb_typeof(media) = 'array'
                    THEN jsonb_array_length(media) <= 5
                    ELSE false
                END),
            created_at timestamptz NOT NULL DEFAULT now(),
            updated_at timestamptz NOT NULL DEFAULT now()
        )
    $create_table$, warden_user_id_type);
END $$;

CREATE INDEX IF NOT EXISTS notices_created_at_idx
    ON public.notices (created_at DESC);

ALTER TABLE public.notices ENABLE ROW LEVEL SECURITY;

